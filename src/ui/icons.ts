// 16x16 pixel icons (SPEC 5.3), drawn by ui/Icon through PixelSprite. Each icon is 16 strings of
// 16 characters. '.' is transparent, '#' is the icon colour (currentColor by default) and '+' is the
// same colour at 40%, for fills and secondary detail. iconPalette builds the palette for a colour.
export type Frame = string[];

export const ICON_NAMES = [
  // UI
  'tick', 'cross', 'clock', 'arrow', 'lock', 'replay', 'pause', 'play',
  // HUD tiles (lesson vars), 'var' is the fallback
  'target', 'need', 'sum', 'index', 'count', 'var',
  // modules (keys used in content/modules.ts)
  'hash', 'pointers', 'stack', 'search', 'list', 'tree', 'graph', 'dp',
] as const;
export type IconName = (typeof ICON_NAMES)[number];

/** Palette for an icon drawn in `color` (any CSS colour, including currentColor and var()). */
export function iconPalette(color: string): Record<string, string> {
  return { '+': `color-mix(in srgb, ${color} 40%, transparent)`, '#': color };
}

